#Requires -Version 5.1
<#
.SYNOPSIS
    The pure half of the drift -> GitHub issue reconciler (tools/New-PfbDriftIssue.ps1).
.DESCRIPTION
    Turns Reports/PfbApiDriftReport.json and Reports/PfbDeadKeyReport.json into one
    fingerprinted finding per atomic gap, groups the findings into issue-sized units, and
    plans the issue writes that reconcile them with what GitHub already holds.

    Nothing here touches the network or the filesystem. The shell script owns every read
    and write, so each rule below is testable against in-memory fixtures
    (Tests/PfbDriftIssueTools.Tests.ps1) with no token and no repository.

    THE FINGERPRINT IS A PUBLIC, PERMANENT KEY. It is stamped into issue bodies on
    github.com, closed issues included, and GitHub issues are the reconciler's only state --
    there is no baseline file. Changing the tuple, a category token, the separator or the
    hash re-keys every stamped issue at once: every open issue's findings "vanish" (the
    restructure guard then aborts every run) and every declined finding becomes eligible to
    be filed again. Treat $script:PfbDriftCategoryToken and Get-PfbDriftFingerprint as
    frozen; the golden values in the test file exist to make an accidental change red.

    5.1-compatible for the same reason as tools/lib/PfbAgentBriefTools.ps1: nothing here
    needs 7, and claiming 7 would make the test file skip on the winps51 leg, which the
    coverage gate would then require to be pinned in Tests/coverage-baseline.psd1.
    Pure ASCII on purpose: PSUseBOMForUnicodeEncodedFile is held at zero repo-wide.
#>

