function Get-PfbGapFieldName {
    <#
    .SYNOPSIS
        Internal helper: the wire name a MissingQueryParameters/MissingBodyProperties list
        ENTRY represents, whether that entry is a bare string (Get-PfbParameterCoverageGaps'
        own, always-bare-string shape) or an enriched record
        (Build-PfbApiDriftReport.ps1's `{ name, type, format, ... }` shape, applied ONLY to
        high-confidence MissingBodyProperties -- see Get-PfbBodyPropertyEnrichment). Kept
        tolerant of both shapes so Get-PfbSystemicGaps works whether it's handed
        Get-PfbParameterCoverageGaps' raw output (this task's own real-data verification) or
        a later, already-enriched report structure (Task 7's job, not this task's).
    .OUTPUTS
        string, or $null if -Entry is neither shape.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [AllowNull()]
        $Entry
    )

    if ($null -eq $Entry) { return $null }
    if ($Entry -is [string]) { return $Entry }
    if ($Entry.PSObject.Properties.Name -contains 'name') { return $Entry.name }
    return $null
}

function Get-PfbSystemicGaps {
    <#
    .SYNOPSIS
        Decision 7: collapses Get-PfbParameterCoverageGaps's per-endpoint
        MissingQueryParameters/MissingBodyProperties lists into ONE finding PER DISTINCT
        WIRE NAME, across every endpoint AND both lists together -- e.g. `context_names`
        showing up as a missing query parameter on 252 different endpoints becomes a
        SINGLE finding with an EndpointCount of 252, not 252 separate per-endpoint rows.
        This is what turns hundreds of individual gap rows into a handful of real,
        actionable decisions.
    .DESCRIPTION
        An endpoint whose SAME field name happens to appear in both its own
        MissingQueryParameters and MissingBodyProperties (measured against the real
        capability map: exactly 1 real case, POST /workloads/placement-recommendations|
        placement_names -- see Get-PfbParameterCoverageGaps's own .OUTPUTS help) still
        contributes that endpoint only ONCE to the name's EndpointCount: endpoints are
        deduplicated per name via a HashSet, never concatenated across the two lists.
        Entries are read through Get-PfbGapFieldName so this tolerates either
        Get-PfbParameterCoverageGaps's own bare-string lists or an already-enriched
        MissingBodyProperties record shape.
    .OUTPUTS
        [PSCustomObject]@{ Name; EndpointCount; Endpoints; QueryEndpointCount;
        BodyEndpointCount }[], sorted by EndpointCount descending, then Name ascending.
        Endpoints is the sorted, deduplicated list of "<METHOD> /<path>" endpoint keys.
        QueryEndpointCount/BodyEndpointCount are the (possibly-overlapping) counts of
        endpoints where the name showed up specifically in MissingQueryParameters /
        MissingBodyProperties -- informational only; EndpointCount is always the
        deduplicated total, never their sum.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [AllowEmptyCollection()]
        [object[]]$Gaps
    )

    # Typed Dictionary[string, T], not a plain Hashtable, for every one of these three maps
    # -- a wire field literally named 'keys'/'count'/'values' would shadow .Keys/.Count/
    # .Values member access on a Hashtable-backed IDictionary (the same hazard
    # Get-PfbParameterCoverageGaps's own $queryFieldVersions/$bodyFieldVersions already
    # avoid, see its comment above them).
    $endpointsByName = [System.Collections.Generic.Dictionary[string, object]]::new()
    $queryCountByName = [System.Collections.Generic.Dictionary[string, int]]::new()
    $bodyCountByName = [System.Collections.Generic.Dictionary[string, int]]::new()

    foreach ($gap in $Gaps) {
        foreach ($rawEntry in @($gap.MissingQueryParameters)) {
            $name = Get-PfbGapFieldName -Entry $rawEntry
            if (-not $name) { continue }
            if (-not $endpointsByName.ContainsKey($name)) { $endpointsByName[$name] = [System.Collections.Generic.HashSet[string]]::new() }
            [void]$endpointsByName[$name].Add($gap.Endpoint)
            if (-not $queryCountByName.ContainsKey($name)) { $queryCountByName[$name] = 0 }
            $queryCountByName[$name] = $queryCountByName[$name] + 1
        }
        foreach ($rawEntry in @($gap.MissingBodyProperties)) {
            $name = Get-PfbGapFieldName -Entry $rawEntry
            if (-not $name) { continue }
            if (-not $endpointsByName.ContainsKey($name)) { $endpointsByName[$name] = [System.Collections.Generic.HashSet[string]]::new() }
            [void]$endpointsByName[$name].Add($gap.Endpoint)
            if (-not $bodyCountByName.ContainsKey($name)) { $bodyCountByName[$name] = 0 }
            $bodyCountByName[$name] = $bodyCountByName[$name] + 1
        }
    }

    $findings = [System.Collections.Generic.List[object]]::new()
    foreach ($name in $endpointsByName.get_Keys()) {
        $endpoints = @($endpointsByName[$name] | Sort-Object)
        $findings.Add([PSCustomObject]@{
                Name               = $name
                EndpointCount      = $endpoints.Count
                Endpoints          = $endpoints
                QueryEndpointCount = if ($queryCountByName.ContainsKey($name)) { $queryCountByName[$name] } else { 0 }
                BodyEndpointCount  = if ($bodyCountByName.ContainsKey($name)) { $bodyCountByName[$name] } else { 0 }
            })
    }

    return @($findings | Sort-Object -Property @{ Expression = 'EndpointCount'; Descending = $true }, Name)
}

function Get-PfbWireNameCmdletCounts {
    <#
    .SYNOPSIS
        Wire name -> the distinct set of cmdlets across the WHOLE module that already
        expose it as a resolved ('Typed') parameter -- the raw data
        Get-PfbConventionStrength ranks names against. Built directly from
        Get-PfbCmdletParameterInventory's own output (tools/lib/PfbCmdletParamTools.ps1);
        this function does not re-derive wire-name resolution itself, per this task's
        brief ("read that file to find the right existing data source rather than
        re-deriving wire-name resolution from scratch").
    .OUTPUTS
        System.Collections.Generic.Dictionary[string, System.Collections.Generic.HashSet[string]]
        -- typed Dictionary, not a plain Hashtable, for the same keys-shadowing reason as
        every other new map in this section (a wire name literally named 'keys' is real:
        see Get-PfbParameterCoverageGaps's own comment for the confirmed example).
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [AllowEmptyCollection()]
        [object[]]$CmdletInventory
    )

    $map = [System.Collections.Generic.Dictionary[string, object]]::new()
    foreach ($row in $CmdletInventory) {
        if ($row.Surface -ne 'Typed' -or -not $row.WireName) { continue }
        if (-not $map.ContainsKey($row.WireName)) { $map[$row.WireName] = [System.Collections.Generic.HashSet[string]]::new() }
        [void]$map[$row.WireName].Add($row.Cmdlet)
    }
    return $map
}

function Get-PfbConventionStrength {
    <#
    .SYNOPSIS
        Decision 8: for each of -Names (typically the field names Get-PfbSystemicGaps just
        surfaced), how many DISTINCT cmdlets across the whole module already expose that
        exact wire name as a resolved ('Typed') parameter somewhere -- a proxy for "how
        mechanical would it be to close the REMAINING gaps for this name". A name already
        used by hundreds of cmdlets (e.g. `names`) is a trivial batch fix on whatever
        stragglers are left; a name used by ZERO cmdlets (e.g. `context_names`) has no
        established convention to extend at all -- closing it is an architectural
        decision, not a mechanical batch job.
    .OUTPUTS
        [PSCustomObject]@{ Name; CmdletCount; Cmdlets }[], one entry per -Names input IN
        THE SAME ORDER (never re-sorted here -- a caller ranks by CmdletCount itself).
        CmdletCount is 0 and Cmdlets is an empty array (never omitted, never $null) for a
        name no cmdlet exposes at all -- that zero IS the finding for names like
        `context_names`.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [AllowEmptyCollection()]
        [object[]]$CmdletInventory,

        [Parameter(Mandatory)]
        [string[]]$Names
    )

    $countsByName = Get-PfbWireNameCmdletCounts -CmdletInventory $CmdletInventory

    foreach ($name in $Names) {
        $cmdlets = if ($countsByName.ContainsKey($name)) { @($countsByName[$name] | Sort-Object) } else { @() }
        [PSCustomObject]@{
            Name        = $name
            CmdletCount = $cmdlets.Count
            Cmdlets     = $cmdlets
        }
    }
}

