                    -- exact wire-field name for matchType 'field' (e.g. "context_names");
                       an endpoint-key SUBSTRING for matchType 'endpoint', matched
                       case-insensitively against the "<METHOD> /<path>" key format (e.g.
                       "management-access-policies" matches every method on that resource).
                "kind": "designDecision" | "priorConclusion" | "liveTestingHazard",
                "note": string,
                    -- human-readable, deliberately never a machine-verified assertion.
                       E.g. allow_errors' note says only "not yet implemented" -- NOT
                       whether its injection would be gated on the endpoint declaring the
                       parameter or sent unconditionally to every endpoint. That specific
                       behavioral question is explicitly deferred to a separate PR (#22)
                       and is not yet decided; this file must never assert either answer.
                "reference": string | null
                    -- a doc path (repo-relative), or null when there's nowhere to point.
              }, ...
            ]
          }
        Easy to extend: append another object to "annotations" -- no code change needed for
        a new entry with an existing "kind"/"matchType" value.
    .OUTPUTS
        The parsed PSCustomObject (schemaVersion/annotations), or $null if -Path doesn't
        exist. Never throws for a missing file -- an absent annotations file means "no
        annotations available (yet)", not a hard error, so a consumer keeps working even
        before this file existed / if it's ever deleted.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$Path
    )

    if (-not (Test-Path $Path)) { return $null }
    return Get-Content -Path $Path -Raw | ConvertFrom-Json -Depth 10
}

function Find-PfbDriftAnnotation {
    <#
    .SYNOPSIS
        Looks up every annotation in -Annotations (Get-PfbDriftAnnotations's output) that
        matches -FieldName (matchType 'field', exact match) and/or -Endpoint (matchType
        'endpoint', case-insensitive substring match against the endpoint key).
    .OUTPUTS
        [PSCustomObject][] -- zero or more matching annotation records, never $null (an
        empty array when -Annotations is $null, has no "annotations" list, or nothing
        matches).
    #>
    [CmdletBinding()]
    param(
        [AllowNull()]
        $Annotations,

        [string]$FieldName,

        [string]$Endpoint
    )

    if (-not $Annotations -or -not $Annotations.annotations) { return @() }

    return @($Annotations.annotations | Where-Object {
            ($_.matchType -eq 'field' -and $FieldName -and $_.match -eq $FieldName) -or
            ($_.matchType -eq 'endpoint' -and $Endpoint -and $Endpoint -like "*$($_.match)*")
        })
}

function Test-PfbExpressionReferencesParameter {
    <#
    .SYNOPSIS
        Internal helper for Get-PfbCentralInjectionSites: true if -ExpressionAst references,
        ANYWHERE within its subtree, a variable whose name is in -ParameterNames (the
        enclosing function's own declared parameter names) -- e.g. `$BoundParameters['Filter']`
        references `$BoundParameters`, or `$Names -join ','` references `$Names`.
    .OUTPUTS
        [bool]
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [System.Management.Automation.Language.Ast]$ExpressionAst,

        [Parameter(Mandatory)]
        [System.Collections.Generic.HashSet[string]]$ParameterNames
    )

    if ($ParameterNames.Count -eq 0) { return $false }

    $varRefs = $ExpressionAst.FindAll({ param($n) $n -is [System.Management.Automation.Language.VariableExpressionAst] }, $true)
    foreach ($v in $varRefs) {
        if ($ParameterNames.Contains($v.VariablePath.UserPath)) { return $true }
    }
    return $false
}

function Test-PfbGuardedByParameterCondition {
    <#
    .SYNOPSIS
        Internal helper for Get-PfbCentralInjectionSites: true if -Assignment sits inside an
        enclosing `if` clause whose test expression, taken AS A WHOLE, is EXACTLY a bare
        parameter reference (`if ($Names)`) or a `.ContainsKey(...)` call on a parameter
        (`if ($BoundParameters.ContainsKey('TotalOnly'))`) -- the two guard shapes
        Private/Add-PfbCommonQueryParams.ps1 actually uses.
    .DESCRIPTION
        Deliberately narrow, not "the condition mentions a parameter anywhere": a condition
        that merely INCLUDES a parameter as one operand of a larger boolean expression --
        e.g. Private/Invoke-PfbApiRequest.ps1's `$AutoPaginate -and $response.continuation_token
        -and -not $limitReached` -- does NOT match here, because $AutoPaginate there gates
        WHETHER pagination happens at all, not WHERE the assigned key's VALUE comes from.
        Only a condition that reduces, whole, to one of the two exact shapes above counts,
        matching the real Add-PfbCommonQueryParams idiom this rule exists to recognize.
    .OUTPUTS
        [bool]
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [System.Management.Automation.Language.Ast]$Assignment,

        [Parameter(Mandatory)]
        [System.Collections.Generic.HashSet[string]]$ParameterNames
    )

    if ($ParameterNames.Count -eq 0) { return $false }

    $node = $Assignment.Parent
    while ($node) {
        if ($node -is [System.Management.Automation.Language.IfStatementAst]) {
            foreach ($clause in $node.Clauses) {
                $withinBody = @($clause.Item2.FindAll({ param($n) $n -eq $Assignment }, $true))
                if ($withinBody.Count -eq 0) { continue }

                # Unwrap the PipelineAst/CommandExpressionAst layers the parser puts around
                # a bare `if (...)` test expression -- same wrapping phenomenon
                # Resolve-PfbSingleExpression (tools/lib/PfbCmdletParamTools.ps1) already
                # peels for an assignment's right-hand side, reused here rather than
                # re-deriving the same unwrap loop.
                $condExpr = Resolve-PfbSingleExpression -Ast $clause.Item1

                $bareVar = $condExpr -as [System.Management.Automation.Language.VariableExpressionAst]
                if ($bareVar -and $ParameterNames.Contains($bareVar.VariablePath.UserPath)) { return $true }

                $memberCall = $condExpr -as [System.Management.Automation.Language.InvokeMemberExpressionAst]
                if ($memberCall -and $memberCall.Member -is [System.Management.Automation.Language.StringConstantExpressionAst] -and
                    $memberCall.Member.Value -eq 'ContainsKey') {
                    $callTarget = $memberCall.Expression -as [System.Management.Automation.Language.VariableExpressionAst]
                    if ($callTarget -and $ParameterNames.Contains($callTarget.VariablePath.UserPath)) { return $true }
                }
            }
        }
        $node = $node.Parent
    }
    return $false
}

function Get-PfbCentralInjectionSites {
    <#
    .SYNOPSIS
        Scans every function in -PrivateDirectory for the same wire-key assignment AST
        shape Get-PfbWireNameForParameter (tools/lib/PfbCmdletParamTools.ps1) already
        recognizes for Public/ cmdlets -- `$Var['key'] = <rhs>`, an IndexExpressionAst on
        the assignment's left side -- restricted to the three variable names this module
        actually uses, Private-side, for a request's wire-level payload hashtable:
        'queryParams' (Invoke-PfbApiRequest's own -QueryParams parameter), 'body' (its
        -Body parameter), and 'into' (Add-PfbCommonQueryParams's -Into parameter, the
        query-params hashtable a Public/ caller passes in by reference).
    .DESCRIPTION
        Deliberately narrower than "every IndexExpressionAst assignment anywhere in
        Private/": this directory also splats plenty of OTHER hashtables that are
        HTTP-transport/SSH plumbing, never spec-documented API fields -- $headers,
        $restParams, $sshParams, $loginParams, $jwtParams, $oauthParams (confirmed by
        direct inspection: Private/Invoke-PfbApiRequest.ps1, Private/Get-PfbApiTokenViaSsh.ps1,
        Private/Invoke-PfbApiTokenLogin.ps1, Private/Invoke-PfbOAuth2Login.ps1). Including
        those would pollute the candidate list with junk like 'Authorization' or
        'AcceptKey' that could never be a capability-map field name in the first place.

        For each matching assignment, classifies whether the assigned VALUE traces back to
        a parameter of the ENCLOSING function:
          - directly, via Test-PfbExpressionReferencesParameter on the right-hand side
            (e.g. `$Into['filter'] = $BoundParameters['Filter']` references $BoundParameters,
            a parameter of Add-PfbCommonQueryParams; `$Into['names'] = $Names -join ','`
            references $Names directly); or
          - via Test-PfbGuardedByParameterCondition, for the one real case where the
            right-hand side is a bare literal but the key's PRESENCE is still gated on a
            parameter (`if ($BoundParameters.ContainsKey('TotalOnly')) { $Into['total_only'] = 'true' }`).
        Anything neither reaches is classified 'server-or-internal-derived' -- e.g.
        Private/Invoke-PfbApiRequest.ps1's own
        `$QueryParams['continuation_token'] = $response.continuation_token`: its RHS
        references `$response` (not a declared parameter of Invoke-PfbApiRequest), and its
        guard condition (`$AutoPaginate -and $response.continuation_token -and -not
        $limitReached`) is a compound `-and` expression, not one of
        Test-PfbGuardedByParameterCondition's two narrow whole-condition shapes, so it does
        not get credited to $AutoPaginate merely because that parameter happens to appear
        in it.

        This is intentionally narrow, not general symbolic data-flow analysis. See this
        function's own Caveat output field (always populated) for the resulting COVERAGE
        (never correctness) claim: this AST scan cannot verify injection ORDERING relative
        to Assert-PfbApiCapability (the module's actual parameter-support gate) -- an
        assignment could in principle run before or after that gate in a way this scan
        does not model.
    .OUTPUTS
        [PSCustomObject]@{ Key; File; Function; Line; TargetVariable; ParameterTraced;
        Classification; Caveat }[] -- Classification is 'parameter-sourced' (traces to a
        cmdlet/caller parameter; must NEVER become a candidate for
        $script:PfbNonActionableParameters) or 'server-or-internal-derived' (a candidate --
        see Get-PfbDerivedNonActionableParameters for how candidates are reduced to a final
        per-key verdict).
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$PrivateDirectory
    )

    $targetVarNames = @('queryparams', 'body', 'into')
    $coverageCaveat = 'coverage claim only -- this AST scan cannot verify injection ordering relative to Assert-PfbApiCapability'

    $results = [System.Collections.Generic.List[object]]::new()
    $files = Get-ChildItem -Path $PrivateDirectory -Filter '*.ps1' -Recurse -File

    foreach ($file in $files) {
        $tokens = $null; $parseErrors = $null
        $ast = [System.Management.Automation.Language.Parser]::ParseFile($file.FullName, [ref]$tokens, [ref]$parseErrors)
        $functionAsts = $ast.FindAll({ param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $true)

        foreach ($funcAst in $functionAsts) {
            $paramBlock = $funcAst.Body.ParamBlock
            $paramNames = [System.Collections.Generic.HashSet[string]]::new([string[]]@(), [System.StringComparer]::OrdinalIgnoreCase)
            if ($paramBlock) {
                foreach ($p in $paramBlock.Parameters) { [void]$paramNames.Add($p.Name.VariablePath.UserPath) }
            }

            $assignments = $funcAst.FindAll({
                    param($n)
                    $n -is [System.Management.Automation.Language.AssignmentStatementAst] -and
                    $n.Left -is [System.Management.Automation.Language.IndexExpressionAst]
                }, $true)

            foreach ($assign in $assignments) {
                $indexExpr = $assign.Left
                $targetVar = $indexExpr.Target -as [System.Management.Automation.Language.VariableExpressionAst]
                if (-not $targetVar) { continue }
                if ($targetVarNames -notcontains $targetVar.VariablePath.UserPath.ToLowerInvariant()) { continue }

                $keyExpr = $indexExpr.Index -as [System.Management.Automation.Language.StringConstantExpressionAst]
                if (-not $keyExpr) { continue }

                $rhsTraced = Test-PfbExpressionReferencesParameter -ExpressionAst $assign.Right -ParameterNames $paramNames
                $conditionTraced = Test-PfbGuardedByParameterCondition -Assignment $assign -ParameterNames $paramNames
                $traced = $rhsTraced -or $conditionTraced
                $classification = if ($traced) { 'parameter-sourced' } else { 'server-or-internal-derived' }

                $results.Add([PSCustomObject]@{
                        Key             = $keyExpr.Value
                        File            = $file.FullName
                        Function        = $funcAst.Name
                        Line            = $assign.Extent.StartLineNumber
                        TargetVariable  = $targetVar.VariablePath.UserPath
                        ParameterTraced = $traced
                        Classification  = $classification
                        Caveat          = $coverageCaveat
                    })
            }
        }
    }

    return $results.ToArray()
}

function Get-PfbDerivedNonActionableParameters {
    <#
    .SYNOPSIS
        Reduces Get-PfbCentralInjectionSites's per-assignment-site output to one verdict
        per distinct wire key: a key becomes a DERIVED non-actionable-parameter candidate
        only when EVERY assignment site found for that key classified
        'server-or-internal-derived' -- if even ONE site for the same key traces to a
        parameter (as filter/sort/limit/total_only/names/ids all do, via
        Private/Add-PfbCommonQueryParams.ps1), the key is excluded from this result, never
        silently added. Excluding those six would be actively harmful, not just imprecise:
        it would silently delete real, still-open gaps on every endpoint/cmdlet that
        doesn't yet expose that parameter (measured against the real capability map: 160
        genuine residual gaps across the six names combined -- 13+35+14+17+35+46).
    .OUTPUTS
        [PSCustomObject]@{ Name; Sites; Caveat; Strength }[], sorted by Name.
        Strength is 'structural' for `continuation_token` specifically (its RHS is
        provably server-response state, `$response.continuation_token` in
        Private/Invoke-PfbApiRequest.ps1 -- can never be sourced from a cmdlet parameter
        even in principle, not merely "not currently seen as a gap") and 'coverage' for
        every other derived key (the general case -- this scan can only claim no OTHER
        Private/ assignment for that key traced to a parameter; it is a coverage claim,
        never a correctness one, per Get-PfbCentralInjectionSites's own Caveat).
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [AllowEmptyCollection()]
        [object[]]$InjectionSites
    )

    $byKey = $InjectionSites | Group-Object -Property Key

    $results = [System.Collections.Generic.List[object]]::new()
    foreach ($group in $byKey) {
        $sites = @($group.Group)
        $anyParameterSourced = [bool]($sites | Where-Object { $_.Classification -eq 'parameter-sourced' })
        if ($anyParameterSourced) { continue }

        $strength = if ($group.Name -eq 'continuation_token') { 'structural' } else { 'coverage' }

        $results.Add([PSCustomObject]@{
                Name     = $group.Name
                Sites    = $sites
                Caveat   = $sites[0].Caveat
                Strength = $strength
            })
    }

    return @($results | Sort-Object Name)
}

function Get-PfbNonActionableParameters {
    <#
    .SYNOPSIS
        The full, up-to-date replacement for reading $script:PfbNonActionableParameters
        directly: the two structurally-confirmed-absent hardcoded entries (X-Request-ID,
        offset -- see the comment above $script:PfbNonActionableParameters for why no
        injection site exists for either) UNIONED with whatever
        Get-PfbCentralInjectionSites/Get-PfbDerivedNonActionableParameters currently derive
        from the real -PrivateDirectory tree -- today, exactly 'continuation_token'.
    .DESCRIPTION
        Callers (e.g. tools/Build-PfbApiDriftReport.ps1's -ExcludedFields) should call this
        function instead of reading $script:PfbNonActionableParameters directly, so a
        future change to Private/Invoke-PfbApiRequest.ps1's injection shape -- e.g. if it
        stopped injecting continuation_token, or started sourcing it from a parameter
        instead of $response -- is reflected automatically the next time this runs, rather
        than silently going stale the way the old hand-written comment could.
    .OUTPUTS
        string[], sorted, deduplicated.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [string]$PrivateDirectory
    )

    # @(...) wraps BOTH calls, not just the final consumption -- the same "assigning a
    # function's output straight to a variable silently collapses a ZERO-element result to
    # $null, not a real empty array/collection" hazard already documented repeatedly
    # elsewhere in this file (e.g. Get-PfbParameterCoverageGaps's $readOnlyList comment).
    # -InjectionSites/-InjectionSites below both carry [AllowEmptyCollection()], which
    # accepts a real empty array but still rejects an outright $null -- confirmed live: a
    # -PrivateDirectory tree with zero matching assignment sites made
    # Get-PfbCentralInjectionSites's `return $results.ToArray()` collapse to $null on
    # assignment here, throwing a ParameterBindingValidationException one call downstream.
    $sites = @(Get-PfbCentralInjectionSites -PrivateDirectory $PrivateDirectory)
    $derived = @(Get-PfbDerivedNonActionableParameters -InjectionSites $sites)
    $derivedNames = @($derived | ForEach-Object { $_.Name })

    return @($script:PfbNonActionableParameters + $derivedNames | Select-Object -Unique | Sort-Object)
}
