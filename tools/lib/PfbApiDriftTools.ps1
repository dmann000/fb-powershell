#     site exists for it either -- confirmed by Get-PfbCentralInjectionSites finding zero
#     assignment sites for this key -- so it stays a hand-written entry: there is nothing
#     to derive an absence FROM.
#   - offset: an alternate, unused positioning mechanism into the same paginated
#     collections -AutoPaginate already retrieves in full; co-occurs with
#     continuation_token on 208/212 of its capability-map endpoints, and zero cmdlets
#     expose it. Same as X-Request-ID: no Private/ injection site exists, so this stays
#     hand-written too.
#
# continuation_token is DELIBERATELY NOT here any more (Task 6) -- it used to be, with a
# hand-written justification identical in spirit to the two above ("superseded by
# Invoke-PfbApiRequest's own -AutoPaginate"). That hand-written comment could go silently
