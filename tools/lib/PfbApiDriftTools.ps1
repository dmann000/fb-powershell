# "coverage, not correctness" caveat (see Get-PfbCentralInjectionSites/
# Get-PfbDerivedNonActionableParameters's own docs): continuation_token is structurally
# unable to ever become a cmdlet parameter, not merely "not currently seen as a gap".
$script:PfbNonActionableParameters = @(
    'X-Request-ID',
    'offset'
)

